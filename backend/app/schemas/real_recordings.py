"""Closed response models for the measured laboratory real-recordings evidence.

The payload is generated by scripts/real_examples.py from attributed Mendeley
recordings (docs/REAL_DATA.md). The route validates the stored file against
these models, so a malformed report is refused as invalid evidence (503)
instead of being served unchecked.
"""

from typing import Literal

from app.schemas.simulation import Closed

FaultLabel = Literal["normal", "unbalance", "misalignment", "looseness"]
MetaLabel = Literal["normal", "unbalance", "misalignment", "looseness", "unknown"]


class ManifestRecording(Closed):
    test: int
    archive: str
    archive_id: str
    archive_sha256_advertised: str
    archive_hash_verified: bool
    member: str
    download_url: str
    recording_sha256: str
    shape: tuple[int, int]
    sample_rate_hz: int


class DatasetManifest(Closed):
    source: Literal["measured_laboratory"]
    dataset_url: str
    doi: str
    license: str
    license_url: str
    attribution: str
    selection: str
    recordings: list[ManifestRecording]


class WaveformPoint(Closed):
    time_ms: float
    amplitude: float


class SpectrumPoint(Closed):
    frequency_hz: float
    amplitude: float


class ChannelFeatures(Closed):
    rms: float
    crest_factor: float
    kurtosis: float
    shaft_1x: float
    shaft_2x: float
    shaft_3x: float


class RealChannel(Closed):
    channel: int
    features: ChannelFeatures
    waveform: list[WaveformPoint]
    spectrum: list[SpectrumPoint]


class Baseline(Closed):
    label: FaultLabel
    distances: dict[str, float]


class MetaEvent(Closed):
    action: Literal["inspect", "diagnose", "error"]
    channel: int | None = None
    reason: str
    raw_response: str | None


class MetaAssessment(Closed):
    label: MetaLabel
    reason: str
    events: list[MetaEvent]
    observed_channels: list[int]
    status: Literal["completed", "model_error"]


class RealRecord(Closed):
    id: str
    label: FaultLabel
    split: Literal["reference", "held_out"]
    provenance: ManifestRecording
    shaft_rpm_estimated: float
    channels: list[RealChannel]
    baseline: Baseline | None = None
    meta: MetaAssessment | None = None


class SupersededRecord(Closed):
    id: str
    label: FaultLabel
    baseline: FaultLabel
    meta: MetaLabel


class SupersededStudy(Closed):
    version: str
    status: str
    plan_sha256: str
    model: str
    reason: str
    baseline_correct: int
    meta_correct: int | None
    meta_accuracy_ci95: tuple[float, float] | None
    held_out_trials: int
    records: list[SupersededRecord]


class RealRecordingsResponse(Closed):
    source: Literal["measured_laboratory"]
    study_version: str
    dataset: DatasetManifest
    sample_rate_hz: int
    duration_s: int
    shaft_rpm_approximate: int
    shaft_rpm_documented: int
    shaft_rpm_estimated_range: tuple[float, float]
    amplitude_units: str
    plan_sha256: str
    reference_trials: int
    held_out_trials: int
    model: str | None
    baseline_correct: int
    meta_correct: int | None
    meta_accuracy_ci95: tuple[float, float] | None
    model_errors: int
    records: list[RealRecord]
    superseded_study: SupersededStudy
    limitations: list[str]
